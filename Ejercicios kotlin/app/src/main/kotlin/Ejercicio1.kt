package org.example.app

fun main(){
    val dato1 = 20
    val dato2 = 10
    var resultado: Int
    resultado = dato1 + dato2
    println("$dato1 + $dato2 = $resultado")
    resultado = dato1 - dato2
    println("$dato1 - $dato2 = $resultado")
    resultado = dato1 * dato2
    println("$dato1 * $dato2 = $resultado")
    resultado = dato1 / dato2
    println("$dato1 / $dato2 = $resultado")
}
